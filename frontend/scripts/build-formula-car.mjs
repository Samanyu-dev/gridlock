/** Original unbranded GRIDLOCK concept: reproducible, no third-party geometry. */
import * as T from 'three'
import { GLTFExporter } from 'three/addons/exporters/GLTFExporter.js'
import { mergeGeometries } from 'three/addons/utils/BufferGeometryUtils.js'
import fs from 'node:fs/promises'
globalThis.FileReader = class {
 readAsArrayBuffer(b){b.arrayBuffer().then(v=>{this.result=v;this.onloadend?.()})}
 readAsDataURL(b){b.arrayBuffer().then(v=>{this.result=`data:${b.type};base64,${Buffer.from(v).toString('base64')}`;this.onloadend?.()})}
}
const out=new URL('../public/models/cars/gridlock-formula/',import.meta.url)
await fs.mkdir(out,{recursive:true})
for(const [quality,n] of [['high',32],['medium',20],['low',12]]){
 const scene=new T.Scene(),root=new T.Group();root.name='GL_Car_Root';scene.add(root)
 const material=(name,color,metalness,roughness)=>{const m=new T.MeshStandardMaterial({color,metalness,roughness});m.name=name;return m}
 const body=material('GL_Mat_Body','#ef233c',.55,.28),trim=material('GL_Mat_Trim','#161c24',.4,.5),tire=material('GL_Mat_Tire','#121316',0,.96),silver=material('GL_Mat_Metal','#a6b3c2',.9,.3),paint=[]
 function part(g,pos,scale,mat=body){g.scale(...scale);g.translate(...pos);if(mat===body)paint.push(g.index?g.toNonIndexed():g);else root.add(new T.Mesh(g,mat))}
 const box=(p,s,m=trim)=>part(new T.BoxGeometry(1,1,1),p,s,m)
 const ell=(p,s,m=body)=>part(new T.SphereGeometry(1,n,n/2),p,s,m)
 function strut(a,b,r=.02){const x=new T.Vector3(...a),y=new T.Vector3(...b),d=y.clone().sub(x),m=new T.Mesh(new T.CylinderGeometry(r,r,d.length(),8),trim);m.position.copy(x.add(y).multiplyScalar(.5));m.quaternion.setFromUnitVectors(new T.Vector3(0,1,0),d.normalize());root.add(m)}
 ell([0,.4,0],[.3,.22,1.05]);ell([0,.30,.92],[.13,.11,.7])
 for(const s of [-1,1]){ell([s*.35,.33,-.28],[.23,.18,.62]);box([s*.42,.45,.17],[.22,.06,.18])}
 ell([0,.52,-.60],[.15,.26,.55]);ell([0,.57,.17],[.19,.10,.31],trim)
 box([0,.18,-.13],[1.14,.06,2.3]);box([0,.24,1.43],[1.60,.055,.26]);box([0,.31,1.38],[1.44,.04,.17])
 for(const s of [-1,1]){box([s*.79,.31,1.43],[.03,.25,.31]);box([s*.64,.70,-1.23],[.035,.40,.35]);strut([s*.21,.29,-1.05],[s*.59,.65,-1.22],.027)}
 box([0,.84,-1.23],[1.30,.06,.32]);box([0,.73,-1.17],[1.23,.04,.23])
 const curve=new T.CatmullRomCurve3([[-.19,.64,-.05],[-.20,.70,.22],[0,.70,.46],[.20,.70,.22],[.19,.64,-.05]].map(p=>new T.Vector3(...p)))
 root.add(new T.Mesh(new T.TubeGeometry(curve,n,.025,6,false),trim));strut([0,.39,.5],[0,.7,.46],.023)
 for(const [z,axle] of [[.94,'F'],[-.94,'R']])for(const [x,side]of [[-.71,'L'],[.71,'R']]){
  const wheel=new T.Group();wheel.name=`GL_Car_Wheel_${axle}${side}`;wheel.position.set(x,.28,z)
  for(const [r,w,m]of [[.28,.25,tire],[.155,.256,silver],[.12,.262,trim]]){const mesh=new T.Mesh(new T.CylinderGeometry(r,r,w,n),m);mesh.rotation.z=Math.PI/2;wheel.add(mesh)}
  root.add(wheel);for(const h of [.25,.4])for(const dz of [-.18,.18])strut([Math.sign(x)*.19,h,z+dz],[x,.28,z],.015)
 }
 const shell=new T.Mesh(mergeGeometries(paint),body);shell.name='GL_Car_Body';root.add(shell)
 const data=await new GLTFExporter().parseAsync(scene,{binary:true});await fs.writeFile(new URL(`${quality}.glb`,out),Buffer.from(data))
 let tris=0;scene.traverse(o=>{if(o.isMesh)tris+=(o.geometry.index?.count??o.geometry.attributes.position.count)/3});console.log(quality,Math.round(tris),'triangles',Math.round(data.byteLength/1024),'KB')
}
await fs.writeFile(new URL('LICENSE.txt',out),'Original procedural GRIDLOCK concept car. Generated by frontend/scripts/build-formula-car.mjs. No third-party model or texture assets. Unbranded design; not an official Formula 1 car.\n')
